const { ethers } = require('ethers');
const fs=require('fs');
const RPC='https://mainnet.base.org';
const NFT='0x96b1394Bd272C36a2078D1cbb1Fc89F8F68b1Be2';
const AASA='0xe4ded569fff9bfd80b131b6ac0d6d0874da5aba3';
const abi=n=>JSON.parse(fs.readFileSync(`build/${n}.json`,'utf8'));
(async()=>{
  const b=JSON.parse(fs.readFileSync('/app/conversations/6ac7cee2e53924ef39e93934/aasa-base/deploy/burner.json','utf8'));
  const p=new ethers.JsonRpcProvider(RPC);
  const w=new ethers.Wallet(b.priv.startsWith('0x')?b.priv:'0x'+b.priv,p);
  const start=await p.getBalance(w.address);
  const gp=(await p.getFeeData()).gasPrice || BigInt(6_000_000);
  console.log('deployer',w.address,'| bal',ethers.formatEther(start),'| gp',ethers.formatUnits(gp,'gwei'),'gwei');
  const a=abi('AvatarRedeemer');
  const f=new ethers.ContractFactory(a.abi,a.bytecode,w);
  const nonce=await p.getTransactionCount(w.address,'pending');
  const c=await f.deploy(NFT,AASA,{gasPrice:gp,nonce});
  await c.waitForDeployment();
  const addr=await c.getAddress();
  const r=await p.getTransactionReceipt(c.deploymentTransaction().hash);
  console.log('AvatarRedeemer v3:',addr,'| gas',r.gasUsed.toString());
  const red=new ethers.Contract(addr,a.abi,p);
  console.log('nft:',await red.nft());
  console.log('aasa:',await red.aasa());
  console.log('paused:',await red.paused());
  console.log('pool:',ethers.formatEther(await red.poolBalance()));
  console.log('phase amounts:',ethers.formatEther(await red.phaseRedeem(0)),ethers.formatEther(await red.phaseRedeem(4)));
  const end=await p.getBalance(w.address);
  console.log('spent',ethers.formatEther(start-end),'ETH | left',ethers.formatEther(end));
  fs.writeFileSync('deployment-v3.json',JSON.stringify({redeemerV3:addr,nft:NFT,aasa:'0xe4deD569fFf9bFD80b131b6aC0D6D0874dA5ABa3',deployer:w.address,tx:c.deploymentTransaction().hash,gasUsed:r.gasUsed.toString(),spentETH:ethers.formatEther(start-end)},null,1));
})().catch(e=>{console.error('FAIL',e.shortMessage||e.message);process.exit(1);});
